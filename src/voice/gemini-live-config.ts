import type {
  FunctionDeclaration,
  LiveConnectConfig,
  Modality,
  StartSensitivity,
} from "@google/genai";
import { parseCommand } from "./commands";
import type { VoiceCommand } from "./types";

/*
 * Shared by the token route (which locks this config into the ephemeral token) and the
 * browser provider. Type-only imports from @google/genai, so importing this file
 * doesn't pull the SDK into the client bundle.
 */

/**
 * API version for ephemeral tokens and Live connections. The Gemini docs (checked Oct
 * 2026) say v1beta; the SDK's own comments still say v1alpha. Change here if needed.
 */
export const LIVE_API_VERSION = "v1beta";

/** One function per patient command. The model only ever picks one; it never speaks to the patient. */
export const LIVE_FUNCTIONS: Readonly<Record<VoiceCommand, string>> = {
  pause: "pause_procedure",
  continue: "continue_procedure",
  repeat: "repeat_instruction",
  call_nurse: "call_study_nurse",
  done: "confirm_step_done",
};

const DESCRIPTIONS: Readonly<Record<VoiceCommand, string>> = {
  pause: 'The person asks to pause or wait ("pause", "wait", "stop", "one moment").',
  continue: 'The person says they are ready to carry on ("continue", "resume", "I\'m ready").',
  repeat: 'The person asks to hear the instruction again ("repeat", "say that again", "what?").',
  call_nurse:
    'The person asks for their nurse or for help, or sounds unwell or distressed ("help", "call my nurse").',
  done: 'The person says they have finished the current step ("done", "finished", "checked", "I did it", "yes").',
};

export function commandForFunction(name: string | undefined): VoiceCommand | null {
  for (const [command, fn] of Object.entries(LIVE_FUNCTIONS) as [VoiceCommand, string][]) {
    if (fn === name) return command;
  }
  return null;
}

const SYSTEM_INSTRUCTION = [
  "You listen to an older adult doing a medical-device training exercise at home.",
  "Your only job is to recognise five spoken commands and call the matching function.",
  "Never answer, chat, explain, reassure, or give any medical or dosing advice. Stay silent.",
  "If the speech is not clearly one of the commands, do nothing.",
  'Never treat "hold" or "hold on" as pause: the exercise includes a press-and-hold step.',
  "If the person sounds unwell, confused or asks for help, call call_study_nurse.",
].join(" ");

/** The locked Live session config. Audio output is generated by the model but never played. */
export function liveConnectConfig(): LiveConnectConfig {
  const functionDeclarations: FunctionDeclaration[] = (
    Object.keys(LIVE_FUNCTIONS) as VoiceCommand[]
  ).map((command) => ({
    name: LIVE_FUNCTIONS[command],
    description: DESCRIPTIONS[command],
    parametersJsonSchema: { type: "object", properties: {} },
  }));
  return {
    responseModalities: ["AUDIO" as Modality],
    temperature: 0,
    systemInstruction: SYSTEM_INSTRUCTION,
    tools: [{ functionDeclarations }],
    inputAudioTranscription: {},
    // Measured against the live API: with default detection, sub-second commands like
    // "I'm done." were never transcribed. High start sensitivity picks them up; false
    // starts are harmless because advancing commands still need our own parser to agree.
    realtimeInputConfig: {
      automaticActivityDetection: {
        startOfSpeechSensitivity: "START_SENSITIVITY_HIGH" as StartSensitivity,
        prefixPaddingMs: 40,
        silenceDurationMs: 600,
      },
    },
  };
}

/** Commands that move the procedure forward need our own parser to agree. */
const ADVANCING = new Set<VoiceCommand>(["continue", "done"]);

/**
 * Cross-checks the model's function calls against what was actually said.
 *
 * - Cautious commands (pause, call_nurse, repeat) are accepted straight away: acting on
 *   a false "pause" is safe, missing a real "help" is not.
 * - Advancing commands (continue, done) are accepted only once the input transcription
 *   parses to the same command with the app's own strict parser. If the transcript
 *   hasn't arrived yet the call waits, and it's dropped when the turn ends.
 * - If the model called nothing in a turn, the transcript goes through the same parser
 *   as the browser path, so Live is never worse at hearing commands.
 *
 * Pure; the provider feeds it server messages.
 */
export class LiveCommandGate {
  private transcript = "";
  private pending: VoiceCommand[] = [];
  private emitted = false;

  constructor(private readonly onCommand: (command: VoiceCommand, transcript: string) => void) {}

  get currentTranscript(): string {
    return this.transcript.trim();
  }

  /** Returns whether the call was accepted now (false = rejected or waiting). */
  onFunctionCall(name: string | undefined): boolean {
    const command = commandForFunction(name);
    if (!command) return false;
    if (!ADVANCING.has(command)) {
      this.emit(command, this.currentTranscript);
      return true;
    }
    if (this.confirms(command)) {
      this.emit(command, this.currentTranscript);
      return true;
    }
    if (!this.pending.includes(command)) this.pending.push(command);
    return false;
  }

  onTranscription(fragment: string): void {
    this.transcript += fragment;
    this.pending = this.pending.filter((command) => {
      if (!this.confirms(command)) return true;
      this.emit(command, this.currentTranscript);
      return false;
    });
  }

  /** Ends the turn; returns the full transcript heard in it. */
  onTurnComplete(): string {
    const heard = this.currentTranscript;
    const parsed = this.emitted ? null : parseCommand(heard);
    this.transcript = "";
    this.pending = [];
    this.emitted = false;
    if (parsed) this.onCommand(parsed, heard);
    return heard;
  }

  private emit(command: VoiceCommand, transcript: string): void {
    this.emitted = true;
    this.onCommand(command, transcript);
  }

  private confirms(command: VoiceCommand): boolean {
    return parseCommand(this.transcript) === command;
  }
}

/** Float32 samples (-1..1) to little-endian 16-bit PCM, base64-encoded. */
export function floatToPcm16Base64(samples: Float32Array): string {
  const bytes = new Uint8Array(samples.length * 2);
  const view = new DataView(bytes.buffer);
  for (let i = 0; i < samples.length; i++) {
    const s = Math.max(-1, Math.min(1, samples[i] ?? 0));
    view.setInt16(i * 2, s < 0 ? s * 0x8000 : s * 0x7fff, true);
  }
  let binary = "";
  for (let i = 0; i < bytes.length; i += 0x8000) {
    binary += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  }
  return btoa(binary);
}
